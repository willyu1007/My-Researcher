#!/usr/bin/env node
// Regenerates the Codex App Server protocol bindings from the codex binary that is installed
// (T-152 D-2: pin the bindings to the binary that runs, no upstream fetch, no version guessing).
//
//   node apps/backend/scripts/codex-app-server-bindings-generate.mjs          # regenerate
//   node apps/backend/scripts/codex-app-server-bindings-generate.mjs --check  # exit 1 on drift
//
// Output: apps/backend/src/generated/codex-app-server/ — `codex app-server generate-ts` verbatim,
// except that relative import specifiers gain `.js` so NodeNext resolution accepts them, plus
// `codex-version.ts` recording which binary produced the tree. Set TOPIC_SELECTION_CODEX_BINARY to
// generate from a binary other than the one on PATH.

import { spawnSync } from 'node:child_process';
import { cp, mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const checkOnly = process.argv.slice(2).includes('--check');
const binary = process.env.TOPIC_SELECTION_CODEX_BINARY?.trim() || 'codex';
const targetDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/generated/codex-app-server');
const VERSION_FILE = 'codex-version.ts';

function codex(args) {
  const result = spawnSync(binary, args, { encoding: 'utf8' });
  if (result.status !== 0) {
    throw new Error(`${binary} ${args.join(' ')} failed (${String(result.status)}): ${result.stderr}`);
  }
  return result.stdout;
}

/** Relative path → content for every file under `dir`, or null when the directory is absent. */
async function snapshot(dir) {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true }).catch(() => null);
  if (entries === null) {
    return null;
  }
  const files = new Map();
  for (const entry of entries) {
    if (entry.isFile()) {
      const absolute = path.join(entry.parentPath, entry.name);
      files.set(path.relative(dir, absolute), await readFile(absolute, 'utf8'));
    }
  }
  return files;
}

const version = codex(['--version']).trim();
const scratch = await mkdtemp(path.join(tmpdir(), 'codex-app-server-bindings-'));
try {
  codex(['app-server', 'generate-ts', '--out', scratch]);
  const generated = await snapshot(scratch);
  for (const [file, source] of generated) {
    // ts-rs emits `from "./Name"` (a file) and `from "./v2"` (a directory); NodeNext needs
    // `./Name.js` and `./v2/index.js`.
    generated.set(file, source.replace(/(from\s+")(\.\.?\/[^"]+)"/g, (_match, prefix, specifier) => {
      const isDirectory = generated.has(path.normalize(path.join(path.dirname(file), specifier, 'index.ts')));
      return `${prefix}${specifier}${isDirectory ? '/index.js' : '.js'}"`;
    }));
  }
  generated.set(VERSION_FILE, [
    '// GENERATED by scripts/codex-app-server-bindings-generate.mjs — do not edit.',
    `export const CODEX_APP_SERVER_BINDINGS_CODEX_VERSION = ${JSON.stringify(version)};`,
    '',
  ].join('\n'));

  const current = await snapshot(targetDir);
  const drift = [...new Set([...(current?.keys() ?? []), ...generated.keys()])]
    .filter((file) => current?.get(file) !== generated.get(file))
    .sort();

  if (checkOnly) {
    if (drift.length === 0) {
      console.log(`[codex-app-server-bindings] OK: bindings match ${version} (${generated.size} files).`);
    } else {
      console.error(
        `[codex-app-server-bindings] STALE: ${String(drift.length)} file(s) differ from what ${version} emits `
        + `(first: ${drift.slice(0, 5).join(', ')}). Regenerate with:\n`
        + '  node apps/backend/scripts/codex-app-server-bindings-generate.mjs',
      );
      // Set, not exited: the scratch tree below must still be removed.
      process.exitCode = 1;
    }
  } else if (drift.length === 0) {
    console.log(`[codex-app-server-bindings] Up to date with ${version}; nothing written.`);
  } else {
    for (const [file, source] of generated) {
      await writeFile(path.join(scratch, file), source, 'utf8');
    }
    await rm(targetDir, { recursive: true, force: true });
    await cp(scratch, targetDir, { recursive: true });
    console.log(`[codex-app-server-bindings] Wrote ${String(generated.size)} files from ${version} (${String(drift.length)} changed).`);
  }
} finally {
  await rm(scratch, { recursive: true, force: true });
}
