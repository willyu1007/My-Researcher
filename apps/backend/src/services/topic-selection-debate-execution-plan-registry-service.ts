/** The provider-option suffixes generated by the model-profile registry's providerOptions(profileKey) for
 *  EVERY debate profile (the deepseek suffix is intentionally absent — it is gated to need-discovery
 *  workers only). The registry test asserts each suffix below actually resolves, so a rename here fails
 *  loudly rather than silently selecting a non-existent option. */
const OPTION_SUFFIX = {
  openaiBalanced: 'openai-balanced',
  openaiQuality: 'openai-quality',
  openaiDeepReasoning: 'openai-deep-reasoning',
  dashscopeThinkingBudget: 'dashscope-thinking-budget',
} as const;

/** A provider_llm execution spec carrying ONE real, profile-key-scoped model_option_id. (execution_mode
 *  'provider_llm' is required by the plan schema whenever a model_option_id is present.) */
function providerSpec(profileKey: string, suffix: string): TopicSelectionAgentExecutionSpec {
  return { execution_mode: 'provider_llm', model_option_id: `${profileKey}.${suffix}` };
}

