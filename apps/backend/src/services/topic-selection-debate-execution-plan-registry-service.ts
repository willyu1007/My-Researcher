// This is the ONLY slice that AUTHORS + SELECTS a plan; S1/S2/S3 only threaded the (absent-by-default)
// plan through N8 / N6 / v1c-N2. Each family gets three named plans (codex_assisted / provider_compact /
// provider_diverse) whose per-role model_option_ids are REAL, profile-key-scoped option ids derived from
// the SAME profile-id constants the model-profile registry uses (so a literal can never drift). The shape
// + resolver + level mapping live in the shared leaf (topic-selection-debate-execution-plan-contracts);
// the concrete provider literals live here, backend-side, next to the model-profile registry.
//
// ──────────────────────────────────────────────────────────────────────────────────────────────────────
// LOUD BOUNDARY — identity/provenance, NOT live provider execution (the single most misread thing here):
//   N8 and N6 debates run codex_assisted | mocked_llm ONLY (their runtime input restricts execution_mode to
//   Extract<…, 'codex_assisted' | 'mocked_llm'>). There is NO live provider_llm debate path in W-09.
//   Therefore a per-role model_option_id selected by one of these plans changes the PROMPT-PACKET IDENTITY
//   and PROVENANCE metadata of the debate — it does NOT change the provider that actually executes. No
//   openai/dashscope call is made for these debates in W-09. A "provider_diverse" run is selectable and
//   identity-bearing, NOT live multi-provider execution. True per-role multi-provider EXECUTION is OUT of
//   W-09 scope.
//
// SCOPE NOTES:
//   - deepseek is structurally UNAVAILABLE on the debate profiles (the registry's deepseek gate covers only
//     the need-discovery explorer/deep-critic profiles). So provider_diverse here = openai-vs-dashscope
//     only; widening the deepseek eligibility set is a registry change deliberately OUT of scope (it would
//     perturb the N6 per-role profile hashes). The "deepseek explorer/critic-eligible, never arbiter" rule
//     is still encoded as a guard test: no plan ever assigns deepseek, and the arbiter/final terminal role
//     always takes the highest-quality openai option, never an alternative-worker provider.
//   - provider_fallback_policy is NOT added: the model-profile registry pins an anti-fallback stance
//     (automatic_fallback:false, provider_failure_result:'blocked', validator-enforced), so an unavailable
//     provider stays "blocked" rather than silently falling back. A per-role fallback list would contradict
//     that v1 stance; deferred until (and if) live provider debate execution lands post-W-09.

